#!/usr/bin/env node
// Aggregates results/<skill>/*.json into REPORT.md: per model pass rate, speed, cost,
// and the lowest-ranked model meeting each skill's floor (skills/<skill>/skill.yaml).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const models = parse(readFileSync(join(root, 'models.yaml'), 'utf-8')).sort((a, b) => a.rank - b.rank);
const read = (...p) => readFileSync(join(root, ...p), 'utf-8');
const pct = (n, d) => (d ? `${Math.round((100 * n) / d)}%` : '-');

function modelStats(runs, floor) {
  const good = runs.filter((r) => r.pass && r.latency_s <= floor.max_latency_s);
  const sorted = runs.map((r) => r.latency_s).sort((a, b) => a - b);
  return {
    n: runs.length,
    pass: runs.filter((r) => r.pass).length,
    good: good.length,
    avg: runs.reduce((s, r) => s + r.latency_s, 0) / runs.length,
    p95: sorted[Math.min(sorted.length - 1, Math.ceil(0.95 * sorted.length) - 1)],
    cost: runs.reduce((s, r) => s + r.cost_usd, 0) / runs.length,
    timeouts: runs.filter((r) => r.timed_out).length,
  };
}

function skillSection(skill) {
  const { floor } = parse(read('skills', skill, 'skill.yaml'));
  const dir = join(root, 'results', skill);
  const files = readdirSync(dir).filter((f) => f.endsWith('.json'));
  const rows = files.flatMap((f) => JSON.parse(read('results', skill, f)).runs);
  const refs = [...new Set(files.map((f) => JSON.parse(read('results', skill, f)).ref))];
  const lines = [
    `## ${skill}`,
    '',
    `Floor: pass rate >= ${floor.min_pass_rate * 100}% within ${floor.max_latency_s}s. Refs: ${refs.join(', ')}.`,
    '',
    '| Model | Runs | Pass | Within floor | Avg s | p95 s | Timeouts | $/run |',
    '|---|---|---|---|---|---|---|---|',
  ];
  let lowest = null;
  let baselineOk = null;
  for (const m of models) {
    const runs = rows.filter((r) => r.model === m.label);
    if (!runs.length) continue;
    const s = modelStats(runs, floor);
    const meets = s.good / s.n >= floor.min_pass_rate;
    if (!lowest && meets) lowest = m.label;
    if (m.baseline) baselineOk = meets;
    lines.push(`| ${m.label} | ${s.n} | ${pct(s.pass, s.n)} | ${pct(s.good, s.n)} | ${s.avg.toFixed(0)} | ${s.p95.toFixed(0)} | ${s.timeouts} | ${s.cost.toFixed(3)} |`);
  }
  const baseline = models.find((m) => m.baseline)?.label;
  if (baselineOk === false) lines.push('', `> Baseline ${baseline} does not meet the floor: fix the skill or the eval before trusting the other rows.`);
  lines.push('', `**Lowest model meeting the floor: ${lowest ?? 'none of the tested models'}**`, '');
  return lines.join('\n');
}

const skills = readdirSync(join(root, 'skills'));
const body = skills.map(skillSection).join('\n');
writeFileSync(join(root, 'REPORT.md'), `# Skill eval report\n\nGenerated by scripts/report.mjs. Models are ranked low to high in models.yaml.\n\n${body}`);
console.log(`REPORT.md written for ${skills.join(', ')}`);
